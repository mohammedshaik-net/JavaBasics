import java.util.*;
public class DataTypesConversion{
    public static void main (String args[]){
        int a=3, b=2, c=1;
        float f=2f;
        double d=3.1;
        System.out.println((float)(a+b+c+f+d));
        System.out.println((double)(a+b));
        System.out.println((int)(d+3));
        char j='A';
        System.out.println(j);
        int L=j;
        System.out.println(L);
        
    
    }
}