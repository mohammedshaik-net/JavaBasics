
import java.util.*;
public class SwappingValuesInVariables
{
    public static void main (String args[]){
        int a, b, temp;
        a=3;
        b=7;
        temp=a;
        a=b;
        b=temp;
        System.out.println("The Value of a is "+a);
        System.out.println("The Value of b is "+b);
 }

}